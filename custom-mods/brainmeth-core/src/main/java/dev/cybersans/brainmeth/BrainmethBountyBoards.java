package dev.cybersans.brainmeth;

import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.mojang.logging.LogUtils;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.storage.LevelResource;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.neoforge.event.entity.player.PlayerInteractEvent;
import net.neoforged.neoforge.event.level.BlockEvent;
import org.slf4j.Logger;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.HashMap;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;

/**
 * Only operators can establish Brainmeth bounty boards. Ordinary players may
 * take and redeem contracts at those boards, but cannot place, break, move,
 * or activate boards generated by vanilla villages or other mechanisms.
 *
 * Authorised board locations are saved with the world, not inferred from
 * board item NBT (which Bountiful preserves on break). This prevents a
 * non-operator from recycling an old board to reroll its contracts.
 */
@EventBusSubscriber(modid = BrainmethCore.MOD_ID)
public final class BrainmethBountyBoards {
    private static final Logger LOGGER = LogUtils.getLogger();
    private static final String BOARD_ID = "bountiful:bountyboard";
    private static final Map<String, Set<Long>> authorised = new HashMap<>();
    private static MinecraftServer loadedServer;

    private BrainmethBountyBoards() {}

    private static boolean isBoard(BlockState state) {
        return BOARD_ID.equals(BuiltInRegistries.BLOCK.getKey(state.getBlock()).toString());
    }

    private static boolean isBoardItem(PlayerInteractEvent.RightClickBlock event) {
        return BOARD_ID.equals(BuiltInRegistries.ITEM.getKey(event.getItemStack().getItem()).toString());
    }

    private static boolean isOperator(ServerPlayer player) {
        return player.hasPermissions(2);
    }

    private static String dimension(ServerLevel level) {
        return level.dimension().location().toString();
    }

    private static boolean isAuthorised(ServerLevel level, BlockPos pos) {
        return authorised.getOrDefault(dimension(level), Set.of()).contains(pos.asLong());
    }

    @SubscribeEvent
    public static void onPlace(BlockEvent.EntityPlaceEvent event) {
        if (!(event.getLevel() instanceof ServerLevel level) || !isBoard(event.getPlacedBlock())) return;
        // Reject non-player placement as well: only an operator's explicit
        // placement can create a playable board.
        if (!(event.getEntity() instanceof ServerPlayer player) || !isOperator(player)) {
            event.setCanceled(true);
            return;
        }
        ensureLoaded(level.getServer());
        authorised.computeIfAbsent(dimension(level), key -> new HashSet<>()).add(event.getPos().asLong());
        save(level.getServer());
    }

    @SubscribeEvent
    public static void onBreak(BlockEvent.BreakEvent event) {
        if (event.isCanceled() || !(event.getLevel() instanceof ServerLevel level)
            || !isBoard(event.getState())) return;
        if (!(event.getPlayer() instanceof ServerPlayer player) || !isOperator(player)) {
            event.setCanceled(true);
            return;
        }
        ensureLoaded(level.getServer());
        Set<Long> positions = authorised.get(dimension(level));
        if (positions != null && positions.remove(event.getPos().asLong())) save(level.getServer());
    }

    @SubscribeEvent
    public static void onUse(PlayerInteractEvent.RightClickBlock event) {
        if (!(event.getLevel() instanceof ServerLevel level)
            || !(event.getEntity() instanceof ServerPlayer player)) return;
        ensureLoaded(level.getServer());

        if (isBoard(level.getBlockState(event.getPos()))) {
            // Everyone may use a board placed by an operator. Existing
            // village-generated or unregistered boards are admin-only.
            if (!isOperator(player) && !isAuthorised(level, event.getPos())) {
                event.setCanceled(true);
                event.setCancellationResult(InteractionResult.FAIL);
            }
            return;
        }

        // Deny before the client tries to place the item. EntityPlaceEvent
        // above is the authoritative fallback for other placement paths.
        if (!isOperator(player) && isBoardItem(event)) {
            event.setCanceled(true);
            event.setCancellationResult(InteractionResult.FAIL);
        }
    }

    private static void ensureLoaded(MinecraftServer server) {
        if (loadedServer == server) return;
        loadedServer = server;
        authorised.clear();
        Path path = file(server);
        if (!Files.exists(path)) return;
        try (var reader = Files.newBufferedReader(path, StandardCharsets.UTF_8)) {
            JsonObject root = JsonParser.parseReader(reader).getAsJsonObject();
            for (String dimension : root.keySet()) {
                Set<Long> positions = new HashSet<>();
                for (var entry : root.getAsJsonArray(dimension)) positions.add(entry.getAsLong());
                authorised.put(dimension, positions);
            }
        } catch (Exception e) {
            LOGGER.error("Cannot load authorised Brainmeth bounty boards; existing boards will be admin-only", e);
        }
    }

    private static Path file(MinecraftServer server) {
        return server.getWorldPath(LevelResource.ROOT).resolve("brainmeth-bounty-boards.json");
    }

    private static void save(MinecraftServer server) {
        JsonObject root = new JsonObject();
        authorised.forEach((dimension, positions) -> {
            JsonArray entries = new JsonArray();
            for (long position : positions) entries.add(position);
            root.add(dimension, entries);
        });
        Path path = file(server);
        Path temp = path.resolveSibling(path.getFileName() + ".tmp");
        try {
            Files.writeString(temp, root.toString() + "\n", StandardCharsets.UTF_8);
            try {
                Files.move(temp, path, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
            } catch (java.nio.file.AtomicMoveNotSupportedException e) {
                Files.move(temp, path, StandardCopyOption.REPLACE_EXISTING);
            }
        } catch (IOException e) {
            LOGGER.error("Cannot save authorised Brainmeth bounty boards", e);
        }
    }
}
